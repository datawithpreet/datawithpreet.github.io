/* Renders the Substack article hub on blog.html from assets/data/substack-posts.json.
   The JSON is generated by scripts/sync_substack.py (daily GitHub Action).
   Full article text lives on Substack; each card links out there, and the
   existing GA4 click tracking in main.js records the click as substack_click. */
(() => {
  const container = document.getElementById('substack-feed');
  if (!container) return;

  const setStatus = (msg) => {
    container.innerHTML = '';
    const p = document.createElement('p');
    p.className = 'feed-status';
    p.textContent = msg;
    container.appendChild(p);
  };

  fetch('assets/data/substack-posts.json', { cache: 'no-store' })
    .then((res) => {
      if (!res.ok) throw new Error('article index not found');
      return res.json();
    })
    .then((data) => {
      const posts = data.posts || [];
      if (!posts.length) {
        setStatus('No articles yet — check back soon.');
        return;
      }

      container.innerHTML = '';

      const meta = document.createElement('p');
      meta.className = 'feed-meta';
      let metaText = posts.length + ' articles · full text lives on Substack';
      if (data.updated_utc) {
        const updated = new Date(data.updated_utc);
        if (!isNaN(updated)) {
          metaText += ' · synced ' + updated.toLocaleDateString(undefined, {
            month: 'short',
            day: 'numeric',
            year: 'numeric',
          });
        }
      }
      meta.textContent = metaText;
      container.appendChild(meta);

      const grid = document.createElement('div');
      grid.className = 'writing-grid';

      posts.forEach((post) => {
        const card = document.createElement('a');
        card.className = 'writing-card';
        card.href = post.url;
        card.target = '_blank';
        card.rel = 'noopener';

        const kicker = document.createElement('span');
        kicker.textContent = (post.date_display || 'SUBSTACK').toUpperCase();
        card.appendChild(kicker);

        const title = document.createElement('h3');
        title.textContent = post.title;
        card.appendChild(title);

        if (post.excerpt) {
          const excerpt = document.createElement('p');
          excerpt.textContent = post.excerpt;
          card.appendChild(excerpt);
        }

        const cta = document.createElement('strong');
        cta.textContent = 'Read on Substack ↗';
        card.appendChild(cta);

        grid.appendChild(card);
      });

      container.appendChild(grid);
    })
    .catch(() => setStatus('Could not load the article list right now — use the Substack link above.'));
})();
